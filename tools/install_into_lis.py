#!/usr/bin/env python3
"""Idempotent local integration into an existing LIS checkout.

Updates the canonical Makefile.am. With --regenerate, calls autoreconf -fi
so Makefile.in is regenerated by autotools, not edited by guessed line offsets.
Never performs git add/commit/push and never touches PR metadata.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import shutil
import subprocess


def insert_after(path: Path, needle: str, insertion: str) -> bool:
    s = path.read_text()
    if insertion.strip() in s:
        return False
    if s.count(needle) != 1:
        raise RuntimeError(f"Unexpected build-file layout: {path}; marker matches {s.count(needle)} times")
    path.write_text(s.replace(needle, needle + insertion, 1))
    return True


def append_once(path: Path, marker: str, section: str) -> None:
    s = path.read_text()
    if marker not in s:
        with path.open("a") as f:
            f.write("\n" + section + "\n")


def preflight_insert(path: Path, needle: str, insertion: str) -> None:
    """Reject incompatible build-file layouts before any installation writes."""
    value = path.read_text()
    if insertion.strip() not in value and value.count(needle) != 1:
        raise RuntimeError(
            f"Incompatible build file: {path}: expected one marker, "
            f"found {value.count(needle)}"
        )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("lis_checkout", type=Path)
    ap.add_argument("--regenerate", action="store_true", help="run autoreconf -fi after adding Makefile.am entries")
    ap.add_argument("--install-ci", action="store_true", help="also install the native integration GitHub Actions workflow")
    args = ap.parse_args()
    target = args.lis_checkout.resolve()
    root = Path(__file__).resolve().parents[1]
    required = [target / "Makefile.am", target / "include/lis.h", target / "src/matrix/Makefile.am",
                target / "src/precon/Makefile.am", target / "test/Makefile.am"]
    if any(not f.exists() for f in required):
        raise SystemExit("Not a compatible LIS source checkout: missing required paths")
    pairs = [
        ("include/lis_condense_core.h", "include/lis_condense_core.h"),
        ("include/lis_condense_lis.h", "include/lis_condense_lis.h"),
        ("include/lis_camfamg_composite_core.h", "include/lis_camfamg_composite_core.h"),
        ("src/matrix/lis_condense_core.c", "src/matrix/lis_condense_core.c"),
        ("src/matrix/lis_condense_lis.c", "src/matrix/lis_condense_lis.c"),
        ("src/precon/lis_camfamg_composite_core.c", "src/precon/lis_camfamg_composite_core.c"),
        ("test/testcondense_core.c", "test/testcondense_core.c"),
        ("test/testcondense_oom.c", "test/testcondense_oom.c"),
        ("test/testcomposite_core.c", "test/testcomposite_core.c"),
        ("test/testcondense_lis.c", "test/testcondense_lis.c"),
        ("tools/check_numeric_reuse_mtx.c", "tools/check_numeric_reuse_mtx.c"),
        ("tools/differential_schur_stdlib.py", "tools/differential_schur_stdlib.py"),
    ]
    # All-stages integration requires upstream's built-in native composite.
    composite_file = target / "src/precon/lis_precon_mfamg_ilutp.c"
    if not composite_file.exists():
        raise SystemExit("Missing native mfamg_ilutp from upstream develop; synchronize develop before installing full CA-MFAMG")
    if "lis_solver_set_mfamg_contact_partition" not in (target / "include/lis.h").read_text():
        raise SystemExit("Missing PR #94 CA-MFAMG API; integrate aggregation before installing composite")
    before = (root / "patches/composite_anchor_before.txt").read_text()
    after = (root / "patches/composite_anchor_after.txt").read_text()
    composite_text = composite_file.read_text()
    if after not in composite_text and composite_text.count(before) != 1:
        raise SystemExit("Incompatible native mfamg_ilutp source; expected anchor not found exactly once")

    # Full preflight BEFORE touching the composite, copying files or editing
    # Makefiles. This is especially important when the upstream build layout
    # changes between releases.
    for src, _ in pairs:
        if not (root / src).is_file():
            raise SystemExit(f"Missing required kit source: {src}")
    for name in ("testca_mfamg_ilutp.sh", "testca_mfamg_profiles.sh", "testcondense_differential.sh"):
        if not (root / "test" / name).is_file():
            raise SystemExit(f"Missing required kit test script: {name}")
    preflight_insert(target / "src/matrix/Makefile.am",
                 "libmatrix_la_SOURCES = lis_matrix.c \\\n",
                 "lis_condense_core.c \\\nlis_condense_lis.c \\\n")

    ci_source = root / ".github/workflows/ca-mfamg-native-integration.yml"
    ci_dest = target / ".github/workflows/ca-mfamg-native-integration.yml"
    if args.install_ci:
        if not ci_source.is_file():
            raise SystemExit("Missing native integration CI workflow in kit")
        if ci_dest.exists() and ci_dest.read_bytes() != ci_source.read_bytes():
            raise SystemExit("Native integration workflow already exists and differs; review manually")

    # All preflight conditions passed; the installation may now write files.
    if after not in composite_text:
        composite_file.write_text(composite_text.replace(before, after, 1))
    for src, dst in pairs:
        source = (root / src).resolve()
        dest = (target / dst).resolve()
        # The installer may itself be applied to the target repository as a
        # patch. Avoid shutil.SameFileError in that standard workflow.
        if source != dest:
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, dest)
    insert_after(target / "src/matrix/Makefile.am",
                 "libmatrix_la_SOURCES = lis_matrix.c \\\n",
                 "lis_condense_core.c \\\nlis_condense_lis.c \\\n")
    append_once(target / "include/Makefile.am", "nobase_include_HEADERS += lis_condense_core.h",
                "nobase_include_HEADERS += lis_condense_core.h lis_condense_lis.h")
    # Test-only composite is distributed as source, but is NOT installed as a
    # public header and is NOT linked into the production preconditioner.
    append_once(target / "include/Makefile.am", "EXTRA_DIST += lis_camfamg_composite_core.h",
                "EXTRA_DIST += lis_camfamg_composite_core.h")
    append_once(target / "src/precon/Makefile.am", "EXTRA_DIST += lis_camfamg_composite_core.c",
                "EXTRA_DIST += lis_camfamg_composite_core.c")
    append_once(target / "test/Makefile.am", "test_PROGRAMS += testcondense_core",
                """# Portable condensation and callback-composition regressions.
test_PROGRAMS += testcondense_core testcomposite_core testcondense_lis testcondense_oom
testcondense_core_SOURCES = testcondense_core.c
testcondense_core_LDADD = $(LDADD) -lm
# Compile the portable core separately with test-only allocation injection.
testcondense_oom_SOURCES = testcondense_oom.c $(top_srcdir)/src/matrix/lis_condense_core.c
testcondense_oom_CFLAGS = $(AM_CFLAGS) -DLIS_SC_TEST_ALLOC_FAIL
testcondense_oom_LDADD = -lm
# Test-only callback core: compile into this test, NOT libprecon.
testcomposite_core_SOURCES = testcomposite_core.c $(top_srcdir)/src/precon/lis_camfamg_composite_core.c
testcondense_lis_SOURCES = testcondense_lis.c
testcomposite_core_LDADD = -lm
testcondense_lis_LDADD = $(LDADD) -lm
TESTS += testcondense_core$(EXEEXT) testcomposite_core$(EXEEXT) testcondense_lis$(EXEEXT) testcondense_oom$(EXEEXT)""")
    append_once(target / "test/Makefile.am", "TESTS += testca_mfamg_ilutp.sh",
                """# End-to-end native contact-aware MFAMG + ILUTP on two Schur matrices.
TESTS += testca_mfamg_ilutp.sh testca_mfamg_profiles.sh
EXTRA_DIST += testca_mfamg_ilutp.sh testca_mfamg_profiles.sh""")
    append_once(target / "test/Makefile.am", "TESTS += testcondense_differential.sh",
                """# Independent stdlib-only randomized differential verification (no NumPy/SciPy).
TESTS += testcondense_differential.sh
EXTRA_DIST += testcondense_differential.sh""")
    append_once(target / "Makefile.am", "EXTRA_DIST += tools/differential_schur_stdlib.py",
                "EXTRA_DIST += tools/differential_schur_stdlib.py")
    for name in ("testca_mfamg_ilutp.sh", "testca_mfamg_profiles.sh", "testcondense_differential.sh"):
        script = target / "test" / name
        shutil.copy2(root / "test" / name, script)
        script.chmod(0o755)
    if args.install_ci:
        ci_dest.parent.mkdir(parents=True, exist_ok=True)
        if not ci_dest.exists():
            shutil.copy2(ci_source, ci_dest)
    if args.regenerate:
        subprocess.run(["autoreconf", "-fi"], cwd=target, check=True)
        for rel, symbol in [("src/matrix/Makefile.in", "lis_condense_core"),
                            ("src/precon/Makefile.in", "lis_camfamg_composite_core"),
                            ("test/Makefile.in", "testcondense_core")]:
            if symbol not in (target / rel).read_text():
                raise RuntimeError(f"Missing generated build entry in {rel}")
    print("Local source installation complete. GitHub untouched. Please review git diff,")
    print("configure/build/check. 'lis_solve' integration still requires native testing.")

if __name__ == "__main__":
    main()
